"""Online co-op's tunic colours: the TWWHD Randomizer's colour masks for HD Link's body textures -> a header the runtime
recolours his texture with (runtime/src/mods/coop_pose.cpp).

    tools/coop_tunic_masks.py     (writes runtime/src/mods/coop_tunic_masks.h)

A mask (.bftex) is a texture laid out exactly as Link.bfres's (640x384, tiled, 10 mips): a colour block's endpoint is
the tunic's (or the hat's: they share that part of the texture) when the mask's is pure red, 0x00F8 read big-endian.
Only that is kept, two bits a block (endpoint 1, endpoint 2), in the texture's block order (BC1, 8 bytes a block).

The masks are the TWWHD Randomizer's (github.com/SuperDude88/TWWHD-Randomizer, customizer/data/Link/color_masks),
MIT licence, Copyright (c) SuperDude88 and contributors.
"""
import os
import struct
import urllib.parse
import urllib.request

COMMIT = "cb7b1c979ac031c8eae91e23fb00fc5f4d042efa"
BASE = f"https://raw.githubusercontent.com/SuperDude88/TWWHD-Randomizer/{COMMIT}/customizer/data/Link/color_masks/"
MASKS = [("kHeroTunic", "heroTunic_linktexS3TC_mask.bftex")]
OUT = os.path.join(os.path.dirname(__file__), "..", "runtime", "src", "mods", "coop_tunic_masks.h")


def bits(d):
    ftex = d.find(b"FTEX", 0x10)
    (fmt,), (size,), (mips,) = (struct.unpack_from(">I", d, ftex + o) for o in (0x18, 0x24, 0x2C))
    block = 8
    data = d[0x2000:0x2000 + size + mips]
    out = bytearray((len(data) // block * 2 + 7) // 8)
    for n, o in enumerate(range(0, len(data), block)):
        for e in range(2):
            if struct.unpack_from(">H", data, o + 2 * e)[0] == 0x00F8:
                out[(2 * n + e) // 8] |= 1 << ((2 * n + e) % 8)
    return fmt, len(data), out


lines = ["// Generated by tools/coop_tunic_masks.py from the TWWHD Randomizer's colour masks (MIT licence,",
         "// Copyright (c) SuperDude88 and contributors; github.com/SuperDude88/TWWHD-Randomizer). Do not edit.",
         "// Per colour block of HD Link's texture (its block order, mips after the image), two bits: endpoint 1, 2.",
         "#pragma once", "#include <cstdint>", "", "namespace mods::coop::masks {", ""]
for name, file in MASKS:
    d = urllib.request.urlopen(BASE + urllib.parse.quote(file)).read()
    fmt, size, b = bits(d)
    lines.append(f"// {file}: GX2 format {fmt:#x}, {size} bytes of image and mips")
    lines.append(f"constexpr uint32_t {name}Bytes = {size};")
    lines.append(f"constexpr uint8_t {name}[{len(b)}] = {{")
    for i in range(0, len(b), 24):
        lines.append("    " + ", ".join(f"0x{x:02X}" for x in b[i:i + 24]) + ",")
    lines += ["};", ""]
lines.append("}  // namespace mods::coop::masks")
open(OUT, "w").write("\n".join(lines) + "\n")
print("wrote", OUT)
